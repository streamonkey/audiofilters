// Build the npm package:
//   1. compile the wasm module and shrink it with wasm-opt
//   2. export the filter metadata from the Rust descriptors
//   3. generate src/generated.ts and compile the TypeScript
//   4. bundle the worklet with the metadata inlined (worklets loaded through
//      addModule() should be self-contained)
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = dirname(dirname(fileURLToPath(import.meta.url)));
const root = dirname(pkg);
const dist = join(pkg, 'dist');
const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { cwd: root, stdio: ['ignore', 'pipe', 'inherit'], ...opts });

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

console.log('building wasm module');
run('cargo', ['build', '--locked', '-p', 'smkaf-wasm', '--target', 'wasm32-unknown-unknown', '--profile', 'wasm']);
run('wasm-opt', [
  '-Oz', '--strip-debug', '--strip-producers', '--strip-target-features',
  'target/wasm32-unknown-unknown/wasm/smkaf.wasm', '-o', join(dist, 'smkaf.wasm'),
]);

console.log('exporting filter metadata');
const metadata = run('cargo', ['run', '--locked', '-q', '-p', 'smkaf-tools', '--', 'metadata']).toString();
const filters = JSON.parse(metadata);
writeFileSync(join(dist, 'filters.json'), JSON.stringify(filters, null, 2));
writeFileSync(
  join(pkg, 'src/generated.ts'),
  `// Generated by scripts/build.mjs from the Rust filter descriptors. Do not edit.\n` +
    `export const FILTERS = ${JSON.stringify(filters, null, 2)} as const;\n`,
);

console.log('compiling typescript');
run(join(pkg, 'node_modules/.bin/tsc'), ['-p', pkg], { stdio: 'inherit' });

const worklet = readFileSync(join(pkg, 'src/worklet.js'), 'utf8');
if (!worklet.includes('__SMKAF_FILTERS__')) throw new Error('worklet placeholder missing');
writeFileSync(join(dist, 'worklet.js'), worklet.replace('__SMKAF_FILTERS__', JSON.stringify(filters)));

console.log(`done: ${filters.length} filters -> ${dist}`);
